/// Test: encrypted endpoints on individual datastream interfaces
///
/// # Prerequisites
/// - (Astarte version 1.5 or higher is required)
/// - A device-owned individual datastream interface containing mappings for all supported data types
///   and with 'encrypted' option set to 'true' is uploaded in Astarte realm 'test'
///
/// # Test execution
/// - Register and connect a device to the 'test' realm
/// - Install a volatile trigger to receive incoming interface data events and subscribe to the
///   related Phoenix channel
/// - Have the device send data for all the interface mappings
///
/// # Expected result
/// - A common shared secret is established between device and Astarte
/// - Data from the device is received in COSE-encrypted BSON format and handled by Astarte without errors
/// - An event is generated by Astarte for each data point sent on any path, and the value of
///   'incoming data' contained in the event payload matches with the corresponding value
///   that was sent on that path. The received event value is in plaintext

#[tokio::test]
#[test_log::test]

async fn encrypted_device_datastream() -> eyre::Result<()> {
    let mut connection = device_room::Connection::new_random()?.connect().await?;

    // TODO remove the sleep :'( Here waiting for secret to be shared
    tokio::time::sleep(Duration::from_secs(2)).await;

    Variant::EncryptedDeviceDatastream
        .run(&mut connection.channel, &mut connection.client)
        .await
}
